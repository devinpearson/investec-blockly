// The block reference for the skill (skills/investec-card-snippets), generated
// from the editor's own block definitions so it can't drift from them.
import { blockCatalogue, examples, templates, type BlockInfo } from "./engine";
import { SNIPPET_FORMAT } from "./format";

const code = (value: unknown) => `\`${String(value)}\``;

function shape(block: BlockInfo): string {
  if (block.output !== false) {
    return `value block, output ${block.output ? block.output.join(" | ") : "any"}`;
  }
  if (block.previousStatement || block.nextStatement) return "statement block";
  return "top-level handler";
}

function describe(block: BlockInfo): string {
  const lines = [
    `### ${block.type}`,
    "",
    `Reads: “${block.text.replace(/\s+/g, " ").trim()}” — ${shape(block)}.`,
  ];
  if (block.tooltip) lines.push("", block.tooltip);
  if (block.placement) lines.push("", `Placement: ${block.placement}`);
  const fields = block.inputs.flatMap((input) => input.fields);
  if (fields.length) {
    lines.push("", "Fields:");
    for (const field of fields) {
      const long = (field.options?.length ?? 0) > 40;
      const options = long
        ? `: one of ${field.options!.length} values, e.g. ${field
            .options!.slice(0, 3)
            .map(([label, value]) => `${code(value)} (${label})`)
            .join(", ")} — the value is the code itself`
        : field.options
          ? `: ${field.options.map(([label, value]) => (label === value ? code(value) : `${code(value)} (${label})`)).join(", ")}`
          : "";
      lines.push(
        `- ${code(field.name)} ${field.kind}, default ${code(JSON.stringify(field.default))}${options}`,
      );
    }
  }
  const inputs = block.inputs.filter((input) => input.kind !== "dummy");
  if (inputs.length) {
    lines.push("", "Inputs:");
    for (const input of inputs) {
      lines.push(
        `- ${code(input.name)} ${input.kind}${input.check ? ` (accepts ${input.check.join(" | ")})` : ""}`,
      );
    }
  }
  if (block.toolboxState) {
    lines.push(
      "",
      "Toolbox default:",
      "```json",
      JSON.stringify(block.toolboxState),
      "```",
    );
  }
  return lines.join("\n");
}

export function blockReference(): string {
  const catalogue = blockCatalogue();
  const categories = [...new Set(catalogue.map((block) => block.category))];
  const parts = [
    "<!-- Generated by `npm run skill:reference` from src/blocks and src/toolbox. Do not edit by hand. -->",
    "",
    SNIPPET_FORMAT,
    "# Blocks",
    "",
    ...categories.flatMap((category) => [
      `## ${category}`,
      "",
      ...catalogue
        .filter((block) => block.category === category)
        .map((block) => describe(block) + "\n"),
    ]),
    "# Templates",
    "",
    "Ready-made statements from the editor's Templates category. Drop one into a handler's CODE input (or chain it with `next`).",
    "",
    ...templates().flatMap((template) => [
      `### ${template.section} — ${template.title}`,
      "",
      "```json",
      JSON.stringify(template.block),
      "```",
      "",
    ]),
    "# Examples",
    "",
    "Complete snippets that ship with the editor (full JSON in examples/).",
    "",
    ...Object.entries(examples).map(
      ([name, example]) =>
        `- **${name}**${example.env?.length ? ` (env: ${example.env.join(", ")})` : ""}: ${example.guide?.summary ?? ""}`,
    ),
    "",
  ];
  return parts.join("\n");
}

/** Example workspaces for the skill's examples/ folder, by file name. */
export function exampleFiles(): Record<string, string> {
  return Object.fromEntries(
    Object.entries(examples).map(([name, example]) => [
      `${name
        .replace(/[^\w]+/g, "-")
        .replace(/^-|-$/g, "")
        .toLowerCase()}.json`,
      JSON.stringify(example.state, null, 2) + "\n",
    ]),
  );
}
